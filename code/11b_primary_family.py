"""Second revision, Section 3. Primary analysis: joint null distribution of the five primary
statistics on the census below 10^18, under the reference model generated by inversion (S = 20,000).

Primary family: D_1000, D_ratio, mean ratio, D_cf and Q_10.
  * D_cf is the mean over K = 40 independent Bernoulli(1/2) labelings of the cross-fitted distance
    (the first revision used 5, whose labeling noise, about 0.0004 for one labeling, could move the
    p-value substantially). The same K is used on the census and in every realization.
  * Q_10 = sum over lags 1..10 of z_h^2, with z_h the excess Spearman autocorrelation of the gap
    ratios at lag h standardized by the null mean and standard deviation at that lag.
All five are computed on the same realizations, so that the family-wise adjustment can use their
joint null distribution: Holm's step-down adjustment, and the single-step min-p global test of
Westfall and Young.

Usage: python code/11b_primary_family.py [R] [workers] [K]
"""
import json, os, sys, time
from multiprocessing import Pool
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import benchmark as B
from common import RESULTS, census_cache

R = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
WORKERS = int(sys.argv[2]) if len(sys.argv) > 2 else 8
K = int(sys.argv[3]) if len(sys.argv) > 3 else 40
SEED = 20261016
NAMES = ["D_1000", "D_ratio", "m_ratio", "D_cf"] + [f"rho_{h}" for h in range(1, 11)]


def vec(g, rng):
    u = g / B.rollmean(g, 1000)
    q = B.ratios(g)
    return np.array([B.sup_dev(u, B.exp_cdf), B.sup_dev(q, B.ratio_cdf), float(q.mean()),
                     B.cross_fit(g, rng, splits=K)] + list(B.rank_acf(q)))


def work(task):
    seed, reps = task
    n, _ = census_cache()
    pos = n.astype(np.float64)
    xk, Lk = B.cumulative_intensity(pos, 20000)
    rng = np.random.default_rng(seed)
    return np.array([vec(B.gen_inverse(xk, Lk, len(pos), rng), rng) for _ in range(reps)])


def pvals(t, D, two):
    """Monte Carlo p-values of t (vector) and of every row of D against the columns of D."""
    R = len(D)
    out_t = np.empty(len(t)); out_D = np.empty_like(D)
    for j in range(len(t)):
        d = D[:, j]
        if two[j]:
            c = d.mean(); a, x = np.abs(d - c), abs(t[j] - c)
        else:
            a, x = d, t[j]
        srt = np.sort(a)
        out_t[j] = (1 + R - np.searchsorted(srt, x, side="left")) / (R + 1)
        out_D[:, j] = (1 + R - np.searchsorted(srt, a, side="left")) / (R + 1)
    return out_t, out_D


def main():
    t0 = time.time()
    n, _ = census_cache()
    g = np.diff(n.astype(np.float64))
    rng = np.random.default_rng(SEED)
    obs = vec(g, rng)
    singles = [B.cross_fit(g, rng, splits=1) for _ in range(200)]
    seq = np.random.SeedSequence(SEED)
    tasks = [(c.generate_state(1)[0], 10) for c in seq.spawn(R // 10)]
    D = []
    with Pool(WORKERS) as pool:
        for i, v in enumerate(pool.imap_unordered(work, tasks)):
            D.append(v)
            if i % 20 == 0:
                print(f"  {10*(i+1)}/{R} at {time.time()-t0:.0f}s", flush=True)
    D = np.vstack(D)
    np.savez_compressed(os.path.join(RESULTS, "11b_primary_family.npz"), names=np.array(NAMES), obs=obs, null=D)
    mu, sd = D[:, 4:].mean(0), D[:, 4:].std(0)
    Q = lambda x: np.sum(((x - mu) / sd) ** 2, axis=-1)                     # noqa: E731
    fam_t = np.array([obs[0], obs[1], obs[2], obs[3], Q(obs[4:])])
    fam_D = np.column_stack([D[:, 0], D[:, 1], D[:, 2], D[:, 3], Q(D[:, 4:])])
    two = [False, False, True, False, False]
    p_t, p_D = pvals(fam_t, fam_D, two)
    order = np.argsort(p_t); holm = np.empty(5); run = 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (5 - rank) * p_t[i])); holm[i] = run
    minp_null = p_D.min(1)
    p_global = float((1 + np.sum(minp_null <= p_t.min())) / (len(D) + 1))
    labels = ["D_1000", "D_ratio", "m_ratio", "D_cf", "Q_10"]
    res = dict(R=len(D), K=K, seed=SEED,
               family={lab: dict(obs=float(fam_t[i]), null_mean=float(fam_D[:, i].mean()),
                                 q025=float(np.quantile(fam_D[:, i], .025)), q975=float(np.quantile(fam_D[:, i], .975)),
                                 p=float(p_t[i]), p_se=B.mc_se(p_t[i], len(D)), p_holm=float(holm[i]))
                       for i, lab in enumerate(labels)},
               global_minp=dict(min_p=float(p_t.min()), p_global=p_global),
               rho=dict(obs=obs[4:].tolist(), null_mean=mu.tolist(), null_sd=sd.tolist(), z=((obs[4:] - mu) / sd).tolist()),
               D_cf_single_labeling=dict(mean=float(np.mean(singles)), sd=float(np.std(singles))),
               elapsed_s=time.time() - t0)
    print(json.dumps({k: v for k, v in res.items() if k != "rho"}, indent=1))
    with open(os.path.join(RESULTS, "11b_primary_family.json"), "w") as fh:
        json.dump(res, fh, indent=1)


if __name__ == "__main__":
    main()
