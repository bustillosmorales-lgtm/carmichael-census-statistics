"""Second revision. Table 5: variance-to-mean ratio of interval counts in the scale defined by the
normalization, for four windows and five interval lengths, against realizations of the reference model
generated by inversion of the cumulative intensity and passed through the identical pipeline. It
replaces the five rank-indexed realizations of the first revision (script 05), whose intensity was
smoothed over 1,000 gaps. The controls are computed at S = 20,000, 2,000 and 1,000; the table uses at
each window the resolution assigned by the rule of script 13 (20,000 at W = 100, 2,000 at W = 1,000,
1,000 at W = 5,000), and 1,000 at W = 20,000, where no resolution is valid and the control is
descriptive. For each cell the control is the mean over R realizations, with its central 95% range.

Calibration: the same computation is applied to K realizations of a Poisson process with the known
smooth mean measure C0 of the census (as in part D of script 12), each against R_CAL realizations of
the reference model estimated from it. The central 95% range of the ratio data/control over the K
realizations is what a true Poisson process gives, and the census ratio is compared with it.

Usage: python code/05b_interval_counts_inversion.py [R] [workers] [K] [R_CAL]
"""
import json
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import benchmark as B
from common import RESULTS, census_cache
from scipy.interpolate import PchipInterpolator

R = int(sys.argv[1]) if len(sys.argv) > 1 else 200
WORKERS = int(sys.argv[2]) if len(sys.argv) > 2 else 3
SEED = 20261018
WINDOWS = (100, 1000, 5000, 20000)
GRID_S = (20000, 2000, 1000)
TABLE_S = {100: 20000, 1000: 2000, 5000: 1000, 20000: 1000}
LENGTHS = (1, 2, 5, 20, 100)
CHUNK = 10
K = int(sys.argv[3]) if len(sys.argv) > 3 else 50
R_CAL = int(sys.argv[4]) if len(sys.argv) > 4 else 20


def vmr_all(gaps):
    out = []
    for ell in LENGTHS:
        for W in WINDOWS:
            t = np.cumsum(gaps / B.rollmean(gaps, W))
            nb = int(t[-1] // ell)
            c, _ = np.histogram(t, bins=np.arange(nb + 1) * ell)
            out.append(float(c.var() / c.mean()))
    return out


def work(task):
    S, seed, reps = task
    rng = np.random.default_rng(seed)
    n, _ = census_cache()
    pos = n.astype(np.float64)
    xk, Lk = B.cumulative_intensity(pos, S)
    return S, [vmr_all(B.gen_inverse(xk, Lk, len(pos), rng)) for _ in range(reps)]


def true_realization(seed):
    n, _ = census_cache()
    grid = 10 ** np.arange(3, 18.01, 0.25)
    Cg = np.searchsorted(n, grid).astype(float)
    f = PchipInterpolator(np.log(grid), np.log(np.maximum(Cg, 0.5)))
    xk = np.exp(np.linspace(np.log(n[0]), np.log(n[-1]), 400001))
    Lk = np.exp(f(np.log(xk)))
    Lk = Lk - Lk[0]
    return xk[0] + np.concatenate(([0.0], np.cumsum(B.gen_inverse(xk, Lk, len(n), np.random.default_rng(seed)))))


def work_cal(task):
    """Ratio data/control in every cell for one true realization, with the control at the table resolution."""
    seed = task
    ss = np.random.SeedSequence(seed)
    base = true_realization(ss.generate_state(1)[0])
    data = np.array(vmr_all(np.diff(base)))
    rng = np.random.default_rng(ss.spawn(1)[0])
    ctrl = {}
    for S in GRID_S:
        xk, Lk = B.cumulative_intensity(base, S)
        ctrl[S] = np.mean([vmr_all(B.gen_inverse(xk, Lk, len(base), rng)) for _ in range(R_CAL)], axis=0)
    k, out = 0, []
    for ell in LENGTHS:
        for W in WINDOWS:
            out.append(data[k] / ctrl[TABLE_S[W]][k])
            k += 1
    return out


def main():
    t0 = time.time()
    n, _ = census_cache()
    data = vmr_all(np.diff(n.astype(np.float64)))
    seq = np.random.SeedSequence(SEED)
    tasks = [(S, c.generate_state(1)[0], CHUNK) for S in GRID_S for c in seq.spawn(R // CHUNK)]
    draws = {S: [] for S in GRID_S}
    with Pool(WORKERS) as pool:
        for S, block in pool.imap_unordered(work, tasks):
            draws[S] += block
    out = dict(R=R, seed=SEED, table_S={str(W): S for W, S in TABLE_S.items()}, by_S={})
    for S in GRID_S:
        d_all = np.array(draws[S])
        cells, k = {}, 0
        for ell in LENGTHS:
            for W in WINDOWS:
                d = d_all[:, k]
                cells[f"{ell},{W}"] = dict(data=data[k], control=float(d.mean()), q025=float(np.quantile(d, 0.025)),
                                          q975=float(np.quantile(d, 0.975)), ratio=data[k] / float(d.mean()),
                                          inside=bool(np.quantile(d, 0.025) <= data[k] <= np.quantile(d, 0.975)))
                k += 1
        out["by_S"][str(S)] = cells
        print(f"S={S}: " + "  ".join(f"{c}: {v['data']:.4f}/{v['control']:.4f}" for c, v in cells.items() if c.startswith("100,")),
              flush=True)
    table = {f"{ell},{W}": dict(out["by_S"][str(TABLE_S[W])][f"{ell},{W}"]) for ell in LENGTHS for W in WINDOWS}
    cal_tasks = [int(c.generate_state(1)[0]) for c in np.random.SeedSequence(SEED + 1).spawn(K)]
    with Pool(WORKERS) as pool:
        cal = np.array(list(pool.imap_unordered(work_cal, cal_tasks)))
    k = 0
    for ell in LENGTHS:
        for W in WINDOWS:
            c = table[f"{ell},{W}"]
            lo, hi = np.quantile(cal[:, k], [0.025, 0.975])
            c.update(poisson_ratio_mean=float(cal[:, k].mean()), poisson_ratio_q025=float(lo), poisson_ratio_q975=float(hi),
                     ratio_inside_poisson=bool(lo <= c["ratio"] <= hi))
            k += 1
    out["table"] = table
    out["calibration"] = dict(K=K, R_cal=R_CAL)
    out["elapsed_s"] = time.time() - t0
    with open(os.path.join(RESULTS, "05b_interval_counts_inversion.json"), "w") as fh:
        json.dump(out, fh, indent=1)
    for W in WINDOWS:
        r = [table[f"{ell},{W}"]["ratio"] for ell in LENGTHS]
        ins = sum(table[f"{ell},{W}"]["inside"] for ell in LENGTHS)
        pr = [(table[f"{ell},{W}"]["poisson_ratio_q025"], table[f"{ell},{W}"]["poisson_ratio_q975"]) for ell in LENGTHS]
        insp = sum(table[f"{ell},{W}"]["ratio_inside_poisson"] for ell in LENGTHS)
        print(f"W={W} (S={TABLE_S[W]}): data/control {min(r):.3f} to {max(r):.3f}, inside control range {ins}/5, "
              f"ratio inside the range of a true Poisson process {insp}/5; Poisson ranges "
              + " ".join(f"[{a:.3f},{b:.3f}]" for a, b in pr))


if __name__ == "__main__":
    main()
